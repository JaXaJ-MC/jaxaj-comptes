-- Comptes JaXaJ MC : brique commune d'authentification de toutes les applications du club.
-- Schéma PostgreSQL « compte », à charger après le schéma « annuaire » de jaxaj-membres :
-- un compte est toujours celui d'une personne de l'annuaire.
--
-- L'appli comptes délivre des jetons signés (JWT). Les autres applications les vérifient avec
-- la clé publique et lisent les droits qu'ils contiennent : application, rôle, périmètre.

create extension if not exists citext;      -- e-mail insensible à la casse
create extension if not exists btree_gist;

create schema compte;

create table compte.compte (
  id                 uuid primary key default gen_random_uuid(),
  personne_id        uuid not null unique references annuaire.personne (id),
  email              citext not null unique,
  mot_de_passe       text,  -- empreinte ; vide tant que l'invitation n'est pas acceptée
  actif              boolean not null default true,
  invite_le          timestamptz,
  active_le          timestamptz,  -- mot de passe choisi pour la première fois
  derniere_connexion timestamptz,
  cree_le            timestamptz not null default now(),
  modifie_le         timestamptz not null default now(),
  check (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

-- Liens à usage unique envoyés par e-mail : invitation (choisir son mot de passe) ou
-- réinitialisation. Le lien contient « selecteur.verificateur » ; seule l'empreinte du
-- vérificateur est stockée, une copie de la base ne permet donc pas d'utiliser un lien.
create table compte.jeton (
  id                 uuid primary key default gen_random_uuid(),
  compte_id          uuid not null references compte.compte (id) on delete cascade,
  usage              text not null check (usage in ('invitation', 'reinitialisation')),
  selecteur          text not null unique,
  verificateur_hash  text not null,
  expire_le          timestamptz not null,
  utilise_le         timestamptz,
  cree_le            timestamptz not null default now()
);

-- Droits : tel compte a tel rôle dans telle application, éventuellement limité à une
-- association (périmètre), sur une période. Exemples :
--   comptes / admin                     gère les comptes de tout le club
--   membres / admin                     tout l'annuaire
--   membres / gestion,  périmètre Béarn les membres du chapitre Béarn
--   membres / accueil,  périmètre Prod. recherche et inscription à l'entrée d'un événement
create table compte.attribution (
  id          uuid primary key default gen_random_uuid(),
  compte_id   uuid not null references compte.compte (id) on delete cascade,
  application text not null check (application ~ '^[a-z][a-z0-9_]*$'),
  role        text not null check (role ~ '^[a-z][a-z0-9_]*$'),
  perimetre   uuid references annuaire.organisation (id),
  periode     daterange not null default daterange(current_date, null),
  cree_le     timestamptz not null default now(),
  exclude using gist (
    compte_id with =, application with =, role with =,
    (coalesce(perimetre, '00000000-0000-0000-0000-000000000000'::uuid)) with =,
    periode with &&
  )
);

-- Jetons de renouvellement (bundle Gesdinet) : permettent d'obtenir un nouveau JWT sans
-- retaper son mot de passe. Stockés sous forme d'empreinte.
create table compte.jeton_renouvellement (
  id            bigint generated by default as identity primary key,
  refresh_token varchar(128) not null unique,
  username      varchar(255) not null,  -- e-mail du compte
  valid         timestamp(0) without time zone not null
);

create trigger maj before update on compte.compte
  for each row execute function annuaire.maj_modifie_le();

-- Droits en vigueur, sous la forme lue par les applications : « application:role » ou
-- « application:role:perimetre ».
create view compte.droit_en_vigueur as
select a.compte_id,
       a.application || ':' || a.role || coalesce(':' || a.perimetre::text, '') as droit
from compte.attribution a
where a.periode @> current_date;
